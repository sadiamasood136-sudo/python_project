
# String
text = "Python Programming"

# Indexing
print(text[0])
print(text[1])
print(text[-1])

# Slicing
print(text[0:6])
print(text[7:18])
print(text[:6])
print(text[7:])
print(text[-11:])

# String methods
print(text.upper())
print(text.lower())
print(text.title())
print(text.replace("Python", "Java"))

# String length
print(len(text))

# Checking a substring
print("Python" in text)
