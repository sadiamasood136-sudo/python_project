
# if statement
age = 20

if age >= 18:
    print("You are an adult")

# if-else statement
number = 7

if number % 2 == 0:
    print("Even number")
else:
    print("Odd number")

# if-elif-else statement
marks = int(input("Enter your marks: "))

if marks >= 80:
    print("Grade A")
elif marks >= 70:
    print("Grade B")
elif marks >= 60:
    print("Grade C")
else:
    print("Needs improvement")
